export const japanesePolicies = japanesePolicyData as Record<keyof typeof policies, Policy>;

// Canonical policy identity supplies the stable key, never a translated title.
// Unknown/custom policies retain their content (also used by shared UI callers).
export function getLocalizedPolicy(policy: Policy, language: 'ko' | 'ja'): Policy {
  if (language === 'ko') return policy;
  const key = (Object.keys(policies) as (keyof typeof policies)[]).find(key => policies[key] === policy);
  return key ? japanesePolicies[key] : policy;
}
